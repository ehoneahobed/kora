import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { afterEach, describe, expect, test } from 'vitest'
// The CI bundle budget (first-visit parity K3) measures a template built by this package's
// scaffolder; its attribution logic is tested here, next to the templates it measures.
import {
	K3_BUDGET_BYTES,
	attributeChunk,
	koraPackages,
	packageOf,
} from '../../../../scripts/bench/bundle-budget.mjs'

let dirs: string[] = []
afterEach(() => {
	for (const dir of dirs) rmSync(dir, { recursive: true, force: true })
	dirs = []
})

function writeJson(path: string, value: unknown): void {
	mkdirSync(dirname(path), { recursive: true })
	writeFileSync(path, JSON.stringify(value))
}

describe('bundle budget', () => {
	test('the budget is the contract K3: 20 KB gzip', () => {
		expect(K3_BUDGET_BYTES).toBe(20_000)
	})

	test.each([
		['../../node_modules/.pnpm/yjs@13.6.30/node_modules/yjs/dist/yjs.mjs', 'yjs'],
		[
			'../node_modules/.pnpm/korajs@file+x/node_modules/@korajs/store/dist/index.js',
			'@korajs/store',
		],
		['../../src/App.tsx', null],
		['vite/preload-helper.js', null],
	])('packageOf(%s) is %s', (source, expected) => {
		expect(packageOf(source)).toBe(expected)
	})

	test('attributes each generated byte to the source its mapping segment names', () => {
		// Line 1: columns 0-3 from korajs, 4-6 from the app. Line 2: unmapped.
		// "AAAA" = [col 0, source +0, line 0, col 0]; "ICAA" = [col +4, source +1, line +0, col +0].
		const code = 'abc;def\n// tail'
		const map = {
			sources: ['../node_modules/.pnpm/korajs@1/node_modules/korajs/dist/x.js', '../src/app.ts'],
			mappings: 'AAAA,ICAA;',
		}
		const { byPackage, koraParts } = attributeChunk(code, map, new Set(['korajs']))
		expect(Object.fromEntries(byPackage)).toEqual({
			korajs: 4,
			'(app and bundler glue)': 4,
			'(unmapped)': 7,
		})
		expect(koraParts).toEqual(['abc;'])
	})

	test('source indexes are relative across lines, and negative deltas decode', () => {
		// Line 1 from source 1 ("ACAA"), line 2 back to source 0 ("ADAA": source -1).
		const map = {
			sources: ['node_modules/yjs/a.js', 'node_modules/korajs/b.js'],
			mappings: 'ACAA;ADAA',
		}
		const { byPackage } = attributeChunk('kk\nyy', map, new Set(['korajs', 'yjs']))
		expect(Object.fromEntries(byPackage)).toEqual({ korajs: 3, yjs: 2 })
	})

	test("Kora's packages: korajs, @korajs/* and their dependencies, never the UI framework", () => {
		const app = mkdtempSync(join(tmpdir(), 'kora-budget-'))
		dirs.push(app)
		writeJson(join(app, 'package.json'), {
			dependencies: {
				korajs: '1',
				'@korajs/react': '1',
				react: '19',
				'lucide-react': '1',
				yjs: '13',
			},
		})
		writeJson(join(app, 'node_modules/korajs/package.json'), {
			dependencies: { '@korajs/sync': '1' },
			peerDependencies: { yjs: '13' },
		})
		writeJson(join(app, 'node_modules/korajs/node_modules/@korajs/sync/package.json'), {
			dependencies: { protobufjs: '7' },
		})
		writeJson(join(app, 'node_modules/protobufjs/package.json'), {})
		writeJson(join(app, 'node_modules/@korajs/react/package.json'), {
			peerDependencies: { react: '19' },
		})
		writeJson(join(app, 'node_modules/react/package.json'), {})
		writeJson(join(app, 'node_modules/yjs/package.json'), { dependencies: { lib0: '0.2' } })
		writeJson(join(app, 'node_modules/lib0/package.json'), {})
		writeJson(join(app, 'node_modules/lucide-react/package.json'), {})
		expect([...koraPackages(app)].sort()).toEqual([
			'@korajs/react',
			'@korajs/sync',
			'korajs',
			'lib0',
			'protobufjs',
			'yjs',
		])
	})
})
